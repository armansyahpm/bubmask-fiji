#!/usr/bin/env python3
"""Copy selected Phase 3 images into a Roboflow upload folder."""

from __future__ import annotations

import argparse
import csv
import json
import shutil
from pathlib import Path

from PIL import Image


def safe_filename(text: str) -> str:
    out = []
    for ch in text:
        if ch.isalnum():
            out.append(ch)
        elif ch in {"-", "_", "."}:
            out.append(ch)
        else:
            out.append("_")
    value = "".join(out)
    while "__" in value:
        value = value.replace("__", "_")
    return value.strip("_")


def copy_rows(project_root: Path, tasks_csv: Path, output_dir: Path) -> list[dict[str, str]]:
    image_dir = output_dir / "images"
    image_dir.mkdir(parents=True, exist_ok=True)
    rows: list[dict[str, str]] = []
    with tasks_csv.open("r", newline="", encoding="utf-8-sig") as handle:
        reader = csv.DictReader(handle)
        for idx, row in enumerate(reader, start=1):
            source = project_root / row["relative_path"]
            if not source.is_file():
                raise FileNotFoundError(f"Missing selected image: {source}")
            suffix = source.suffix.lower()
            dest_name = safe_filename(f"{idx:03d}_{row['image_id']}{suffix}")
            dest = image_dir / dest_name
            shutil.copy2(source, dest)
            with Image.open(dest) as image:
                width, height = image.size
                mode = image.mode
            out_row = {
                "upload_filename": dest_name,
                "image_id": row["image_id"],
                "source_relative_path": row["relative_path"],
                "particle_class": row["particle_class"],
                "experiment_group": row["experiment_group"],
                "target_objects": row["target_objects"],
                "required_annotation_geometry": row["required_annotation_geometry"],
                "target_labels": row["target_labels"],
                "width_px": str(width),
                "height_px": str(height),
                "image_mode": mode,
            }
            rows.append(out_row)
    return rows


def write_csv(path: Path, rows: list[dict[str, str]]) -> None:
    if not rows:
        return
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-root", default=".", help="bubmask-fiji project root")
    parser.add_argument(
        "--tasks-csv",
        default="validation/phase3_unsw_validation/annotation_tasks.csv",
        help="Annotation task CSV generated by Phase 3 manifest builder",
    )
    parser.add_argument(
        "--output-dir",
        default="validation/phase3_unsw_validation/roboflow_upload_50",
        help="Output folder to receive selected images",
    )
    args = parser.parse_args()

    project_root = Path(args.project_root).resolve()
    tasks_csv = (project_root / args.tasks_csv).resolve()
    output_dir = (project_root / args.output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    rows = copy_rows(project_root, tasks_csv, output_dir)
    write_csv(output_dir / "roboflow_upload_manifest.csv", rows)
    summary = {
        "schema_version": "bubmask.roboflow_upload.v1",
        "image_count": len(rows),
        "source_tasks_csv": str(tasks_csv),
        "image_folder": str(output_dir / "images"),
        "recommended_project_type": "Instance Segmentation",
        "recommended_export_format": "COCO Segmentation",
        "annotation_policy": "Draw both masks/polygons and boxes where possible. Only high-contrast measurable bubbles should be bubble_valid.",
    }
    (output_dir / "roboflow_upload_summary.json").write_text(
        json.dumps(summary, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print(f"Copied {len(rows)} images to {output_dir / 'images'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
